# 1) صيغة معكوسة (نظام دائرة العطاءات 43/2020 كما استُخرج من PDF)
gtd = """نظام دائرة العطاءات الحكومية
يسѧѧѧمى هѧѧѧذا النظѧѧѧام ( نظـѧѧѧـام دائѧѧѧـرة الـعطѧѧѧـاءات الـحكѧѧѧـومية لسѧѧѧنة  - ١المѧѧѧادة
) ويعمل به من تاريخ نشره في الجريدة الرسمية. ٢٠٢٠
يكون للكلمات التالية حيثما وردت في هذا النظام المعѧѧاني المخصصѧѧة  - ٢المادة
لها أدناه ما لم تدل القرينة على غير ذلك وهذا النص طويل بما يكفي لاختبار التقسيم والجودة
تنشأ دائرة تسمى (دائѧѧرة العطѧѧاءات الحكوميѧѧة) يكѧѧون لها جهازها - أ- ٣المادة
ويرتبط بالوزير ويتولى المهام والواجبات المنصوص عليها في هذا النظام وفي الأنظمة الأخرى.
"""
clean = clean_extracted(gtd)
arts = split_articles(clean)
print("المواد:", [(n, t[:25].replace("\n", " ")) for n, t in arts])
assert [n for n, _ in arts if n != "0"] == ["1", "2", "3"], arts

