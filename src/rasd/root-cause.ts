export const CONFIDENCE_LABELS: Record<Confidence, string> = { high: "ثقة مرتفعة", medium: "ثقة متوسطة", low: "ثقة منخفضة" };

export const isRootCauseCategory = (v: unknown): v is RootCauseCategory =>
  typeof v === "string" && Object.prototype.hasOwnProperty.call(ROOT_CAUSE_LABELS, v);

export interface RootCause {
  category: RootCauseCategory;
  label: string;
  confidence: Confidence;
  /** صياغة السبب الجذري الجاهزة لحقل «السبب» في الملاحظة */
  statement: string;
  /** سلسلة «لماذا» من الحالة المرصودة إلى السبب الجذري */
  whys: string[];
  /** المعالجة التي تزيل السبب لا العَرَض */
  fix: string;
  /** ما بُني عليه التصنيف */
  evidence: string[];
  source: "rules" | "ai";
}

export interface RootCauseInput {
  /** عنوان الاختبار أو الملاحظة */
  test: string;
  /** وصف الحالة (اختياري) */
  condition?: string | undefined;
  /** عدد الحالات المرصودة */
  count?: number | undefined;
  /** عدد الحالات التي وردت في تقارير سابقة */
  repeated?: number | undefined;
}

