const PRIORITY_INDEX = new Map(PRIORITY.map((c, i) => [c, i]));

export function analyzeRootCause(input: RootCauseInput): RootCause {
  const test = input.test.trim() || "الحالة المرصودة";
  const text = norm(`${input.test} ${input.condition ?? ""}`);
  const count = Math.max(0, Math.floor(input.count ?? 1));
  const repeated = Math.max(0, Math.floor(input.repeated ?? 0));

  const score = new Map<Exclude<RootCauseCategory, "undetermined">, number>();
  const evidence = new Map<Exclude<RootCauseCategory, "undetermined">, string[]>();
  const add = (c: Exclude<RootCauseCategory, "undetermined">, w: number, why: string) => {
    score.set(c, (score.get(c) ?? 0) + w);
    evidence.set(c, [...(evidence.get(c) ?? []), why]);
  };

  for (const s of SIGNALS) if (s.re.test(text)) add(s.category, s.weight, s.why);
  if (repeated > 0) add("oversight", 4, `ورد ${repeated > 1 ? `${repeated} من الحالات` : "ما يشبه الحالة"} في تقارير سابقة، فالسبب لم يُعالج`);
  if (count >= 10) {
    add("control_design", 1, `عدد الحالات ${count}: نمط منتظم يدل على خلل في الضابط لا على خطأ فردي`);
    add("oversight", 1, `استمرار ${count} حالة دون رصد مبكر`);
  } else if (count >= 5) {
    add("control_design", 1, `عدد الحالات ${count}: نمط يتجاوز الخطأ الفردي`);
  } else if (count <= 1 && repeated === 0) {
    add("competency", 1, "حالة منفردة غير متكررة، ويرجَّح أنها خطأ فردي");
  }

  const ranked = [...score.entries()].sort(
    (a, b) => b[1] - a[1] || (PRIORITY_INDEX.get(a[0]) ?? 99) - (PRIORITY_INDEX.get(b[0]) ?? 99),
  );
  const top = ranked[0];
  if (!top || top[1] < 2) {
    return {
      category: "undetermined",
      label: ROOT_CAUSE_LABELS.undetermined,
      confidence: "low",
      statement: UNDETERMINED.statement(test),
      whys: UNDETERMINED.whys(test),
      fix: UNDETERMINED.fix,
      evidence: ["لم تطابق الملاحظة نمطاً معروفاً"],
      source: "rules",
    };
  }
  const [category, best] = top;
  const margin = best - (ranked[1]?.[1] ?? 0);
  const confidence: Confidence = best >= 5 && margin >= 2 ? "high" : best >= 3 && margin >= 1 ? "medium" : "low";
  const t = TEMPLATES[category];
  return {
    category,
    label: ROOT_CAUSE_LABELS[category],
    confidence,
    statement: t.statement(test),
    whys: t.whys(test),
    fix: t.fix,
    evidence: evidence.get(category) ?? [],
    source: "rules",
  };
}
